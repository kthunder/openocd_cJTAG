#define CH32_STS_WRPRTERR	8u
#define CH32_STS_VERIFY_FAIL	0x10u

#define CH32_PAGE_SIZE		256u
#define CH32_BUFFER_SIZE	4096u
#define CH32_STACK_SIZE		64u


/***************************************************************************
 *   WCH CH32 / CH5xx (QingKe RISC-V) internal flash driver                *
 *                                                                         *
 *   Programming is delegated to a small position independent loader that  *
 *   WCH pushes into target RAM - exactly the blobs WCH-LinkE and          *
 *   MounRiver Studio use.  The loader is started like any other OpenOCD   *
 *   flash algorithm:                                                      *
 *                                                                         *
 *       a0 = operation flags (CH32_OP_*), a1 = address, a2 = length       *
 *                                                                         *
 *   It returns a status in a0 (0 = ok, 8 = write protected, 0x10 =        *
 *   verify mismatch) and terminates with `ebreak`, which puts the hart    *
 *   back into debug mode.  OpenOCD enables dcsr.ebreakm by default, so    *
 *   no special target support is needed.                                  *
 *                                                                         *
 *   The loader itself hard-codes the RAM buffer it reads data from and    *
 *   the page size it programs, hence they are part of the per-family      *
 *   description below.                                                    *
 *                                                                         *
 *   NOTE: the blobs are dumped from the WCH-LinkE / MounRiver traffic     *
 *   (see ch32-rs/wlink, src/flash_op.rs) - not written from scratch.      *
 ***************************************************************************/


struct ch32_family {
	const char *name;
	const uint8_t *algo;
	uint32_t algo_size;
	uint32_t ram_buffer;		/* data buffer hard-coded in the loader */
	uint32_t ram_checksum;		/* checksum cell used by the verify path */
	uint32_t page_size;		/* bytes programmed per loader iteration */
	uint32_t max_transfer;		/* bytes the loader eats per run */
	uint32_t flash_base;
	uint32_t default_size_kb;	/* fallback if ESIG is unprogrammed */
	uint32_t chip_id_mask;
	uint32_t chip_id_value;
};


static bool ch32_ranges_overlap(uint32_t a_start, uint32_t a_len,
		uint32_t b_start, uint32_t b_len)
{
	return a_start < b_start + b_len && b_start < a_start + a_len;
}

static const struct ch32_family *ch32_family_by_name(const char *name)
{
	for (size_t i = 0; i < ARRAY_SIZE(ch32_families); i++) {
		if (!strcasecmp(ch32_families[i].name, name))
			return &ch32_families[i];
	}
	return NULL;
}

static const struct ch32_family *ch32_family_by_id(uint32_t chip_id)
{
	for (size_t i = 0; i < ARRAY_SIZE(ch32_families); i++) {
		if ((chip_id & ch32_families[i].chip_id_mask) ==
				ch32_families[i].chip_id_value)
			return &ch32_families[i];
	}
	return NULL;
}

static const char *ch32_status_str(uint32_t status)
{
	switch (status) {
	case CH32_STS_OK:
		return "ok";
	case CH32_STS_WRPRTERR:
		return "write protected";
	case CH32_STS_VERIFY_FAIL:
		return "verify mismatch";
	default:
		return "unknown error";
	}
}

/**
 * Run the loader once.
 *
 * @param flags		CH32_OP_* operation mask
 * @param address	flash address the operation applies to
 * @param length	number of bytes
 * @param timeout_ms	how long to wait for the terminating ebreak
 * @param result	optional, receives the loader status from a0
 */
static int ch32_run_algo(struct flash_bank *bank, uint32_t flags,
		uint32_t address, uint32_t length, unsigned int timeout_ms,
		uint32_t *result)
{
	struct target *target = bank->target;
	struct ch32_flash_bank *info = bank->driver_priv;
	const struct ch32_family *family = info->family;
	struct working_area *algo_wa = NULL;
	struct working_area *stack_wa = NULL;
	struct reg_param reg_params[4];
	uint32_t status = CH32_STS_OK;
	int retval;

	if (target->state != TARGET_HALTED) {
		LOG_ERROR("ch32: target must be halted to run the flash loader");
		return ERROR_TARGET_NOT_HALTED;
	}

	retval = target_alloc_working_area(target, family->algo_size, &algo_wa);
	if (retval != ERROR_OK) {
		LOG_ERROR("ch32: no working area for the %u byte flash loader, "
				"raise -work-area-size", (unsigned int)family->algo_size);
		return retval;
	}

	retval = target_alloc_working_area(target, CH32_STACK_SIZE, &stack_wa);
	if (retval != ERROR_OK) {
		LOG_ERROR("ch32: no working area for the loader stack");
		goto out_free_algo;
	}

	/*
	 * The loader reads its data from a fixed address.  OpenOCD hands out
	 * working areas from the bottom of the configured work area, so this
	 * normally does not collide - but be loud about it if it does.
	 */
	if (ch32_ranges_overlap((uint32_t)algo_wa->address, algo_wa->size,
				family->ram_buffer, CH32_BUFFER_SIZE) ||
			ch32_ranges_overlap((uint32_t)stack_wa->address, stack_wa->size,
				family->ram_buffer, CH32_BUFFER_SIZE)) {
		LOG_ERROR("ch32: working area at 0x%08" PRIx32 " overlaps the loader "
				"data buffer at 0x%08" PRIx32 ", lower -work-area-size",
				(uint32_t)algo_wa->address, family->ram_buffer);
		retval = ERROR_TARGET_RESOURCE_NOT_AVAILABLE;
		goto out_free_stack;
	}

	retval = target_write_buffer(target, algo_wa->address,
			family->algo_size, family->algo);
	if (retval != ERROR_OK)
		goto out_free_stack;

	init_reg_param(&reg_params[0], "a0", 32, PARAM_IN_OUT);
	init_reg_param(&reg_params[1], "a1", 32, PARAM_OUT);
	init_reg_param(&reg_params[2], "a2", 32, PARAM_OUT);
	init_reg_param(&reg_params[3], "sp", 32, PARAM_OUT);

	buf_set_u32(reg_params[0].value, 0, 32, flags);
	buf_set_u32(reg_params[1].value, 0, 32, address);
	buf_set_u32(reg_params[2].value, 0, 32, length);
	buf_set_u32(reg_params[3].value, 0, 32, stack_wa->address + stack_wa->size);

	LOG_DEBUG("ch32: loader flags=0x%02" PRIx32 " addr=0x%08" PRIx32
			" len=0x%" PRIx32, flags, address, length);

	retval = target_run_algorithm(target, 0, NULL, (int)ARRAY_SIZE(reg_params),
			reg_params, algo_wa->address, 0, timeout_ms, NULL);
	if (retval != ERROR_OK) {
		LOG_ERROR("ch32: flash loader failed: %d", retval);
	} else {
		status = buf_get_u32(reg_params[0].value, 0, 32);
		if (status != CH32_STS_OK)
			LOG_ERROR("ch32: flash loader reported %s (0x%02" PRIx32 ")",
					ch32_status_str(status), status);
	}

	for (size_t i = 0; i < ARRAY_SIZE(reg_params); i++)
		destroy_reg_param(&reg_params[i]);

	if (retval == ERROR_OK && status != CH32_STS_OK)
		retval = ERROR_FLASH_OPERATION_FAILED;

	if (result)
		*result = status;

out_free_stack:
	target_free_working_area(target, stack_wa);
out_free_algo:
	target_free_working_area(target, algo_wa);
	return retval;
}

FLASH_BANK_COMMAND_HANDLER(ch32_flash_bank_command)
{
	if (CMD_ARGC < 6)
		return ERROR_COMMAND_SYNTAX_ERROR;

	struct ch32_flash_bank *info = calloc(1, sizeof(*info));
	if (!info)
		return ERROR_FAIL;

	if (CMD_ARGC > 6) {
		info->family = ch32_family_by_name(CMD_ARGV[6]);
		if (!info->family) {
			LOG_ERROR("ch32: unknown chip family '%s'", CMD_ARGV[6]);
			free(info);
			return ERROR_COMMAND_ARGUMENT_INVALID;
		}
	}

	bank->driver_priv = info;
	bank->write_start_alignment = 4;
	bank->write_end_alignment = 4;

	return ERROR_OK;
}

static int ch32_probe(struct flash_bank *bank)
{
	struct ch32_flash_bank *info = bank->driver_priv;
	struct target *target = bank->target;
	uint16_t flash_size_kb = 0;
	unsigned int num_sectors;

	if (!info->family) {
		uint32_t chip_id = 0;

		if (target_read_u32(target, CH32_CHIP_ID_ADDR, &chip_id) == ERROR_OK) {
			info->chip_id = chip_id;
			info->family = ch32_family_by_id(chip_id);
		}
		if (!info->family) {
			LOG_ERROR("ch32: unknown chip id 0x%08" PRIx32
					", pass the family explicitly: "
					"flash bank <name> ch32 <base> <size> 0 0 <target> "
					"[ch32x035|ch32v30x|ch32h41x]", chip_id);
			return ERROR_FAIL;
		}
		LOG_INFO("ch32: detected %s (chip id 0x%08" PRIx32 ")",
				info->family->name, chip_id);
	}

	free(bank->sectors);
	bank->sectors = NULL;
	free(bank->prot_blocks);
	bank->prot_blocks = NULL;

	if (target_read_u16(target, CH32_ESIG_FLASH_SIZE, &flash_size_kb) != ERROR_OK ||
			flash_size_kb == 0 || flash_size_kb == 0xffff ||
			flash_size_kb > 4096) {
		LOG_DEBUG("ch32: ESIG flash size unusable, using %" PRIu32 " KiB",
				info->family->default_size_kb);
		flash_size_kb = info->family->default_size_kb;
	}

	if (bank->size == 0 || bank->size == 0xffffffffu) {
		bank->size = (uint32_t)flash_size_kb * 1024u;
		LOG_INFO("ch32: flash size %" PRIu32 " KiB", (uint32_t)flash_size_kb);
	} else if (bank->size > (uint32_t)flash_size_kb * 1024u) {
		LOG_WARNING("ch32: bank size 0x%" PRIx32 " exceeds the %" PRIu32
				" KiB reported by ESIG, clamping", bank->size,
				(uint32_t)flash_size_kb);
		bank->size = (uint32_t)flash_size_kb * 1024u;
	}

	if (bank->base == 0)
		bank->base = info->family->flash_base;

	bank->size -= bank->size % info->family->page_size;
	num_sectors = bank->size / info->family->page_size;
	bank->sectors = alloc_block_array(0, info->family->page_size, num_sectors);
	if (!bank->sectors)
		return ERROR_FAIL;
	bank->num_sectors = num_sectors;

	info->probed = true;

	return ERROR_OK;
}

static int ch32_auto_probe(struct flash_bank *bank)
{
	struct ch32_flash_bank *info = bank->driver_priv;

	if (info->probed)
		return ERROR_OK;
	return ch32_probe(bank);
}

static int ch32_erase(struct flash_bank *bank, unsigned int first,
		unsigned int last)
{
	uint32_t address, length;

	if (bank->target->state != TARGET_HALTED) {
		LOG_ERROR("ch32: target must be halted to erase flash");
		return ERROR_TARGET_NOT_HALTED;
	}
	if (last < first || last >= bank->num_sectors)
		return ERROR_FLASH_SECTOR_INVALID;

	if (first == 0 && last == bank->num_sectors - 1) {
		LOG_DEBUG("ch32: chip erase");
		return ch32_run_algo(bank, CH32_OP_UNLOCK | CH32_OP_ERASE_ALL,
				0, 0, CH32_ERASE_TIMEOUT_MS, NULL);
	}

	address = bank->base + bank->sectors[first].offset;
	length = bank->sectors[last].offset + bank->sectors[last].size -
		bank->sectors[first].offset;

	LOG_DEBUG("ch32: erase 0x%08" PRIx32 "..0x%08" PRIx32, address,
			address + length - 1);

	return ch32_run_algo(bank, CH32_OP_UNLOCK | CH32_OP_ERASE_PAGE,
			address, length, CH32_ERASE_TIMEOUT_MS, NULL);
}

static int ch32_write(struct flash_bank *bank, const uint8_t *buffer,
		uint32_t offset, uint32_t count)
{
	struct ch32_flash_bank *info = bank->driver_priv;
	const struct ch32_family *family = info->family;
	struct target *target = bank->target;
	uint8_t page_buffer[CH32_BUFFER_SIZE];
	uint32_t done = 0;
	int retval;

	if (target->state != TARGET_HALTED) {
		LOG_ERROR("ch32: target must be halted to write flash");
		return ERROR_TARGET_NOT_HALTED;
	}
	if (!count)
		return ERROR_OK;
	if (offset + count > bank->size) {
		LOG_ERROR("ch32: write beyond end of flash");
		return ERROR_FLASH_DST_OUT_OF_BANK;
	}

	while (done < count) {
		uint32_t address = bank->base + offset + done;
		uint32_t page_offset = address % family->page_size;
		uint32_t chunk_start = address - page_offset;
		uint32_t chunk_left = count - done + page_offset;
		uint32_t chunk_len = (chunk_left + family->page_size - 1) /
			family->page_size * family->page_size;
		uint32_t copy_len;

		if (chunk_len > family->max_transfer)
			chunk_len = family->max_transfer;

		copy_len = chunk_len - page_offset;
		if (copy_len > count - done)
			copy_len = count - done;

		/*
		 * Only whole pages are programmed, so read back the pages we are
		 * about to touch and merge the new data into them.  Reading erased
		 * flash simply returns 0xff, so this is safe for the common case
		 * of a freshly erased bank as well.
		 */
		retval = target_read_buffer(target, chunk_start, chunk_len,
				page_buffer);
		if (retval != ERROR_OK) {
			LOG_ERROR("ch32: failed to read back 0x%" PRIx32 " bytes at 0x%08" PRIx32,
					chunk_len, chunk_start);
			return retval;
		}
		memcpy(page_buffer + page_offset, buffer + done, copy_len);

		retval = target_write_buffer(target, family->ram_buffer,
				chunk_len, page_buffer);
		if (retval != ERROR_OK) {
			LOG_ERROR("ch32: failed to fill the loader buffer");
			return retval;
		}

		retval = ch32_run_algo(bank, CH32_OP_UNLOCK | CH32_OP_PROGRAM,
				chunk_start, chunk_len, CH32_WRITE_TIMEOUT_MS, NULL);
		if (retval != ERROR_OK)
			return retval;

		done += copy_len;
	}

	return ERROR_OK;
}


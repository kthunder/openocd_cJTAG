static int cw32_erase(struct flash_bank *bank, unsigned int first,
						unsigned int last)
{
	log_info("%s", __func__);
	int retval = 0;
	struct target *target = bank->target;
	if (!fls_algo_params.init) 
	{
		fls_algo_params.init = true;
		cw32_load_fls_algo(bank);
	}

	int64_t run_algo_start = timeval_ms();

	for (int i = first; i <= last; i++) {
		uint32_t addr = bank->base + bank->sectors[i].offset;

		struct reg_param reg_params[4];
		/* set up parameters */
		init_reg_param(&reg_params[0], "r0", 32, PARAM_IN);
		init_reg_param(&reg_params[1], "r1", 32, PARAM_IN);
		init_reg_param(&reg_params[2], "r2", 32, PARAM_IN);
		init_reg_param(&reg_params[3], "sp", 32, PARAM_IN);

		buf_set_u32(reg_params[0].value, 0, 32, 1);
		buf_set_u32(reg_params[1].value, 0, 32, addr);
		buf_set_u32(reg_params[2].value, 0, 32, 0);
		buf_set_u32(reg_params[3].value, 0, 32, 0x00022000-8);


		/* use alg to write data from work area to NAND chip */
		log_info("erase sector addr %08X", addr);
		struct armv7m_algorithm armv7m_info;	
		armv7m_info.common_magic = ARMV7M_COMMON_MAGIC;
		armv7m_info.core_mode = ARM_MODE_THREAD;	
		struct armv7m_common *armv7m = target_to_armv7m(target);	
		uint32_t res[0x1000] = {1};
		
		target_read_buffer(target, 0x00020170, sizeof(res), res);
		res[0] = 0x10000000;
		target_read_buffer(target, 0x0002016c, sizeof(res), res);
		armv7m->store_core_reg_u32(target, ARMV7M_PC, 0x20000);
		armv7m->load_core_reg_u32(target, ARMV7M_PC, res);
		log_info("PC %08X.", res[0]);
		// target_read_buffer(target, 0x20000, 0x200, res);
		// log_hex("ram", res, 0x200);
		retval = target_run_algorithm(target,
									0, NULL,
									0, NULL,
									0x20000,
									__BKPT,
									10000, &armv7m_info);
		// target_read_buffer(target, 0x20000, 0x200, res);
		// log_hex("ram", res, 0x200);
		armv7m->load_core_reg_u32(target, ARMV7M_PC, res);
		log_info("PC %08X.", res[0]);
		armv7m->load_core_reg_u32(target, ARMV7M_R0, res);
		log_info("R0 %08X.", res[0]);
		target_read_buffer(target, addr, sizeof(res), res);
		log_info("Read back check erase addr %08X : %08X.", addr, res[0]);
		if (retval != ERROR_OK)
			LOG_ERROR("error executing hosted NAND write");

		destroy_reg_param(&reg_params[0]);
		destroy_reg_param(&reg_params[1]);
		// destroy_reg_param(&reg_params[2]);
	}

	log_info("run erase algo %" PRId64 " ms.[%d sectors]", timeval_ms() - run_algo_start, last - first + 1);

	if (retval != ERROR_OK)
	{
		LOG_ERROR("Failed to execute algorithm at 0x%" PRIx32 ": %"PRId32"",
				  fls_algo_params.func_end, retval);
	}

	log_info("%s end", __func__);
	return retval;
}


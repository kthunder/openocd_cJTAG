	// 								10000, &armv7m_info);
	// 	if (retval != ERROR_OK)
			// LOG_ERROR("error executing hosted NAND write");

		destroy_reg_param(&reg_params[0]);
		// destroy_reg_param(&reg_params[1]);
		// destroy_reg_param(&reg_params[2]);

		// log_info("run program algo %" PRId64 " ms.", timeval_ms() - write_data_start);

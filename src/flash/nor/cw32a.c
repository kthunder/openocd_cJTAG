		retval = target_write_buffer(target, source->address,len, buffer);
		// log_info("load program data %" PRId64 " ms.[0x%X bytes]", timeval_ms() - write_data_start, len);
		if (retval != ERROR_OK)
			break;

		struct reg_param reg_params[4];
		/* set up parameters */
		init_reg_param(&reg_params[0], "r0", 32, PARAM_IN);
		init_reg_param(&reg_params[1], "r1", 32, PARAM_IN);
		init_reg_param(&reg_params[2], "r2", 32, PARAM_IN);
		init_reg_param(&reg_params[3], "sp", 32, PARAM_IN);

		buf_set_u32(reg_params[0].value, 0, 32, address);
		buf_set_u32(reg_params[1].value, 0, 32, len);
		buf_set_u32(reg_params[2].value, 0, 32, source->address);
		buf_set_u32(reg_params[3].value, 0, 32, 0x00022000-8);
	
	// armv7m_info.common_magic = ARMV7M_COMMON_MAGIC;
